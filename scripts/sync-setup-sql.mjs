// Copies the idempotent "safety net" migration into src/lib/generated so the
// app can offer it as a one-click "copy SQL" fix when the live database is
// missing something. The migration file stays the single source of truth:
//   npm run sync:setup-sql
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "supabase", "migrations", "0018_budget_schema_safety_net_and_settings.sql");
const target = join(root, "src", "lib", "generated", "setupSql.ts");

const sql = readFileSync(source, "utf8").replace(/\r\n/g, "\n").trimEnd();
// Escape for a JS template literal: backslashes, backticks, and "${".
const escaped = sql.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  "// GENERATED by scripts/sync-setup-sql.mjs from supabase/migrations/0018_*.sql -- do not edit by hand.\n" +
    "export const SETUP_SQL = `" +
    escaped +
    "\n`;\n"
);
console.log(`Wrote ${target} (${sql.length} chars)`);
